const existing = existsSync(OUT)
  ? JSON.parse(readFileSync(OUT, 'utf8'))
  : { descriptions: {} }

const descriptions = {}

// keep only Russian wiki/cache hits
for (const [name, e] of Object.entries(existing.descriptions || {})) {
  if (e?.text && looksRussian(e.text)) {
    descriptions[name] = { text: e.text, lang: e.lang || 'ru', source: e.source }
  }
}
for (const [name, e] of Object.entries(cache)) {
  if (e?.text && looksRussian(e.text) && !descriptions[name]) {
    descriptions[name] = {
      text: e.text,
      lang: e.lang || 'ru',
      source: e.source || 'wikipedia',
    }
  }
}

for (const [name, text] of Object.entries(SEED)) {
  const entry = {
    text: shorten(text),
    lang: 'ru',
    source: 'seed/ru',
  }
  cache[name] = entry
  descriptions[name] = {
    text: entry.text,
    lang: 'ru',
    source: entry.source,
  }
}

const out = {
  updatedAt: new Date().toISOString(),
  count: Object.keys(descriptions).length,
  descriptions,
}
writeFileSync(OUT, JSON.stringify(out))
writeFileSync(CACHE, JSON.stringify(cache))
